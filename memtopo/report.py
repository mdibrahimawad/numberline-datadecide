"""Numbers for REPORT.md: gates, ladder tables, deltas, and the pre-registered verdicts,
written to <out_root>/results/summary.md. The narrative REPORT.md is written by hand from it."""

from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

from memtopo.config import REPO_ROOT, paths, read_gates


def leakage_grep() -> list[str]:
    """Control 4: every place in memtopo/ that picks a checkpoint for features. The asserts in
    pipeline.stage_scans / stage_features enforce ckpt <= S_f; this lists them for the report."""
    hits = []
    for f in sorted((REPO_ROOT / "memtopo").glob("*.py")):
        for n, line in enumerate(f.read_text().splitlines(), 1):
            if re.search(r"leakage|<= sf|exposure_ckpts\(", line):
                hits.append(f"{f.name}:{n}: {line.strip()}")
    return hits


def verdict_h1(d: pd.DataFrame, model: str, sf: int) -> str:
    s = d[(d["comparison"] == "7 vs 6") & (d["subset"] == "hard") & (d["clf"] == "lr")]
    if s.empty:
        return "not run"
    ok = (s["CI_lo"] > 0).all()
    txt = "; ".join(f"seed {r.seed}: ΔAUROC {r.dAUROC:+.4f} [{r.CI_lo:+.4f}, {r.CI_hi:+.4f}], DeLong p={r.DeLong_p:.3g}"
                    for r in s.itertuples())
    return ("SUPPORTED" if ok else "NOT SUPPORTED") + f" ({model}, S_f={sf}; {txt})"


def write_summary(cfg: dict) -> Path:
    p = paths(cfg)
    g = read_gates(p)
    lines = ["# E10 results summary (generated by `python -m memtopo.cli report`)", ""]
    lines += ["## Gates and checked facts", "", "```json"]
    import json
    lines += [json.dumps(g, indent=1, default=str)[:20000], "```", ""]
    verdicts = {}
    for d in sorted((p.root / "results").glob("*/S*")):
        model, sf = d.parent.name, int(d.name[1:])
        lines += [f"## {model}, S_f = {sf}", ""]
        for name in ("ladder", "deltas", "residual", "effects", "velocity", "gaussian_floor",
                     "ladder_mem_final", "deltas_mem_final"):
            f = d / f"{name}.csv"
            if f.exists():
                df = pd.read_csv(f)
                if name.startswith("ladder"):
                    df = df[df["clf"] == "lr"].drop(columns=["target"], errors="ignore")
                lines += [f"### {name}", "", df.round(4).to_markdown(index=False), ""]
        if (d / "deltas.csv").exists():
            verdicts[(model, sf)] = verdict_h1(pd.read_csv(d / "deltas.csv"), model, sf)
    lines += ["## Pre-registered H1 verdicts (7 vs 6, hard subset, LR, out-of-time test)", ""]
    lines += [f"- {v}" for v in verdicts.values()]
    need = [("1b", 10000), ("1b", 23000), ("410m", 10000)]
    strong = all(verdicts.get(k, "").startswith("SUPPORTED") for k in need)
    lines += ["", f"**Success criterion (H1 at 1b/10000, 1b/23000 and 410m/10000, controls clean):** "
              f"{'met, subject to the controls below' if strong else 'not met (partial at most)'}", ""]
    lines += ["## Control 4: leakage (code lines that choose checkpoints)", "", "```"] + leakage_grep() + ["```", ""]
    out = p.root / "results" / "summary.md"
    out.write_text("\n".join(lines))
    return out
